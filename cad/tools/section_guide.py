         '<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Barlow+Condensed:wght@500;600;700'
         '&family=IBM+Plex+Sans:wght@400;500;600&family=IBM+Plex+Mono:wght@400;500;600&display=swap">',
         f'<style>{CSS}</style>', '<body>', '<div class="wrap">',
         '<header class="top">',
         f'<a class="back" href="{e(home)}">← SLR-1 design review</a>',
