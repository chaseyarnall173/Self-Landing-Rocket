         'Each section opens with X-ray views rendered from the CAD, with the skin see-through and every part numbered. '
         'The cards below each view say what the part is for, what it is made of and what it weighs.</p>',
         '<div class="legend"><span class="k"><span class="ball">7</span> number on the views = card number</span>'
         '<span class="k"><span class="dash"></span> dashed leader: part hidden behind others</span>'
         f'<span><a href="{e(viewer)}" target="_blank" rel="noopener">Open the 3D viewer</a> and pick <i>Sections</i> to orbit these live</span></div>',
