def load():
    parts = json.load(open(CAD / "out" / "viewer" / "parts.json"))["parts"]
    render = {r["key"]: r for r in json.load(open(CAD / "out" / "viewer" / "sections_render.json"))}
    out = []
    for S in SECTIONS:
        R = render[S["key"]]
        rows = []
        for r in R["parts"]:
            m = parts[r["pid"]]
            rows.append(dict(pid=r["pid"], num=r["num"], view=r["view"], hidden=not r["px"], short=m["short"],
                             role=m["role"], name=m["name"], qty=m["qty"], mass=m["mass_g"],
                             made=f'{MAKE.get(m["process"], m["process"])} · {MATERIAL.get(m["material"], m["material"])}'))
        views = []
        for v, V in enumerate(S["views"]):
            t = V.get("title") or (f"view {v + 1}" if len(S["views"]) > 1 else "")
            views.append(dict(img=f'{S["key"]}-{v + 1}.png', title=t,
                              nums=[x["num"] for x in rows if x["view"] == v]))
        mass = sum(x["mass"] * x["qty"] for x in rows)
        out.append(dict(S=S, rows=rows, views=views, mass=mass, pieces=sum(x["qty"] for x in rows)))
    return out


def fmt_mass(g):
    return f"{g:.1f}" if g < 10 else f"{g:.0f}"


def markdown(data):
    n_parts = sum(len(d["rows"]) for d in data)
    L = ["# 14. Section by section", "",
         f"Every part of SLR-1, bay by bay: {n_parts} parts in {len(data)} sections. Each section has X-ray views",
         "rendered from the CAD, with the outer skin see-through and every part numbered. The numbers match",
         "the table under the views. A dashed leader points to a part hidden behind others.", "",
         "Masses are from the CAD (catalogue masses for bought parts). *Qty* counts every copy on the rocket.",
         "The same guide is on the project website, and the interactive viewer",
         "([docs/13](13-cad.md)) has a *Sections* mode that draws these callouts live.", ""]
    for i, d in enumerate(data, 1):
        L.append(f"- [14.{i} {d['S']['title']}](#14{i}-{slug(d['S']['title'])})")
    L.append("")
    for i, d in enumerate(data, 1):
        S = d["S"]
        L += [f"## 14.{i} {S['title']}", "", S["intro"], "",
              f"**{len(d['rows'])} parts, {d['pieces']} pieces, {d['mass']:.0f} g.**", ""]
        for v in d["views"]:
            cap = f"{S['title']}" + (f": {v['title']}" if v["title"] else "")
            L += [f"![{cap}](img/sections/{v['img']})", ""]
        L += ["| | # | Part | What it does | Made from | Qty | Mass (g) |",
              "|---|---:|---|---|---|---:|---:|"]
        for r in d["rows"]:
            img = f'<img src="img/parts/{r["pid"]}.png" width="96" alt="{html.escape(r["short"])}">'
            L.append(f"| {img} | {r['num']} | **{r['short']}**<br>`{r['pid']}` | {r['role']} | {r['made']} "
                     f"| {r['qty']} | {fmt_mass(r['mass'])} |")
        L.append("")
    L += ["---", "", "Generated by `python cad/tools/section_guide.py` from `cad/slr1/sections.py` and the CAD build.",
          "Images: `node cad/tools/render_sections.mjs <three-package-dir> docs/img` ([docs/13](13-cad.md#137-rebuilding-and-changing-the-design)).", ""]
    return "\n".join(L)


def slug(t):
    return "".join(c for c in t.lower().replace(" ", "-") if c.isalnum() or c == "-")


