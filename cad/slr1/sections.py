def check(all_pids):
    """Every part must be in exactly one section and have a description."""
    seen = {}
    for s in SECTIONS:
        for p in s["pids"]:
            assert p not in seen, f"{p} in {seen[p]} and {s['key']}"
            seen[p] = s["key"]
    missing = sorted(set(all_pids) - set(seen))
    undescribed = sorted(set(all_pids) - set(PARTS))
    return missing, undescribed
