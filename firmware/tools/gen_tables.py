"""Generate firmware/src/core/motor_tables.h (thrust curves for the flight
computer) and firmware/test/native/golden.h (expected guidance outputs
computed by the Python simulator, used by the native C++ unit tests).

    python firmware/tools/gen_tables.py
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "sim"))

from rocketsim import FlightComputer, GuidanceConfig  # noqa: E402
from rocketsim.designs import motor, slr1  # noqa: E402

CORE = ROOT / "firmware" / "src" / "core"
TEST = ROOT / "firmware" / "test" / "native"


def c_array(name: str, values) -> str:
    body = ", ".join(f"{v:.5f}f" for v in values)
    return f"static const float {name}[] = {{{body}}};"


def motor_block(var: str, name: str) -> str:
    m = motor(name)
    t = list(m.t)
    f = list(m.f)
    return "\n".join([
        f"// {m.summary()}",
        c_array(f"{var}_T", t),
        c_array(f"{var}_F", f),
        f"static const MotorCurve {var} = {{{var}_T, {var}_F, {len(t)}, "
        f"{m.propellant_kg:.5f}f, {m.total_kg:.5f}f}};",
    ])


def main() -> None:
    hdr = [
        "// AUTO-GENERATED by firmware/tools/gen_tables.py from sim/data/motors/*.eng",
        "// Do not edit by hand. Source: ThrustCurve.org RASP files.",
        "#pragma once",
        '#include "motor_curve.h"',
        "",
        motor_block("MOTOR_F42T", "AeroTech_F42T"),   # ascent
        "",
        motor_block("MOTOR_F25W", "AeroTech_F25W"),   # landing
        "",
        motor_block("MOTOR_G40W", "AeroTech_G40W"),   # earlier 500 ft design
        "",
    ]
    (CORE / "motor_tables.h").write_text("\n".join(hdr) + "\n")

    # ----------------------------------------------------- guidance goldens
    v = slr1()
    g = GuidanceConfig()
    ca_fixed = v.ca_tail_first + sum(c.ca for c in v.components if not c.deployable)
    g.cda_burn_m2 = ca_fixed * v.ref_area
    g.cda_pre_m2 = (ca_fixed + sum(c.ca for c in v.components if c.deployable)) * v.ref_area
    g.cda_legs_m2 = v.leg_ca_deployed * v.ref_area
    mb, cgb, ib = v.mass_props(v.ascent_motor.burn_time, None)
    fc = FlightComputer(cfg=g, landing_motor=v.landing_motor, ascent_motor=v.ascent_motor,
                        dry_mass_kg=v.dry_mass_kg, inertia_kgm2=ib,
                        gimbal_lever_m=v.gimbal_station_m - cgb)
    t1, t2 = fc.landing_window()
    lines = [
        "// AUTO-GENERATED by firmware/tools/gen_tables.py - expected values from",
        "// the Python simulator (sim/rocketsim/guidance.py) for the native tests.",
        "#pragma once",
        f"static const float G_DRY_MASS = {v.dry_mass_kg:.6f}f;",
        f"static const float G_ASCENT_CASING = {v.ascent_motor.casing_kg:.6f}f;",
        f"static const float G_CDA_PRE = {g.cda_pre_m2:.6f}f;",
        f"static const float G_CDA_BURN = {g.cda_burn_m2:.6f}f;",
        f"static const float G_KMIN = {g.throttle_min:.6f}f;",
        f"static const float G_CDA_LEGS = {g.cda_legs_m2:.6f}f;",
        f"static const float G_INERTIA = {ib:.6f}f;",
        f"static const float G_LEVER = {v.gimbal_station_m - cgb:.6f}f;",
        f"static const float G_FIRE_WINDOW_FRAC = {g.fire_window_frac:.6f}f;",
        f"static const float G_WINDOW_T1 = {t1:.6f}f;",
        f"static const float G_WINDOW_T2 = {t2:.6f}f;",
        "struct PlanCase { float h, v, rho, tb, tl, k0, k1; };",
        "static const PlanCase PLAN_CASES[] = {",
    ]
    for h, vv, tb, tl in [(15.0, -22.0, 0.0, 1.6), (8.0, -14.0, 0.5, 1.5),
                          (3.0, -7.0, 1.0, 1.6), (20.0, -22.7, 0.0, 1.78)]:
        k0, k1 = fc.plan(h, vv, 1.2, tb, tl)
        lines.append(f"    {{{h}f, {vv}f, 1.2f, {tb}f, {tl}f, {k0:.6f}f, {k1:.6f}f}},")
    lines.append("};")
    # "Strong then simmer" exponential plan: (h, v, tb, t_land, tau_frac) -> k at
    # three points of the profile and the net acceleration at touchdown.
    lines.append("struct ExpCase { float h, v, rho, tb, tl, f, k_first, k_mid, k_last, a_end; };")
    lines.append("static const ExpCase EXP_CASES[] = {")
    for h, vv, tb, tl, f in [(8.0, -18.0, 0.1, 1.6, 0.35), (5.0, -12.0, 0.3, 1.5, 0.25),
                             (3.0, -7.0, 0.6, 1.7, 0.5)]:
        _, _, _, k, a_end = fc.plan_exp(h, vv, 1.2, tb, tl, f, 1.0, g.cda_burn_m2)
        n = len(k)
        lines.append(f"    {{{h}f, {vv}f, 1.2f, {tb}f, {tl}f, {f}f, {k[0]:.6f}f, "
                     f"{k[n // 2]:.6f}f, {k[-1]:.6f}f, {a_end:.6f}f}},")
    lines.append("};")
    # Fire decision: highest altitude (at the airbrake descent speed) where
    # fire_now() is true.
    v_fire = -18.5
    h_fire = None
    for i in range(1200, 0, -1):
        h = i * 0.05
        if fc.fire_now(h, v_fire, 1.2):
            h_fire = h
            break
    lines.append(f"static const float G_FIRE_V = {v_fire}f;")
    lines.append(f"static const float G_FIRE_ALT = {h_fire:.3f}f;")
    (TEST / "golden.h").write_text("\n".join(lines) + "\n")
    print("wrote", CORE / "motor_tables.h", "and", TEST / "golden.h")
    print(f"window [{t1:.3f}, {t2:.3f}] s, fire altitude at {-v_fire} m/s: {h_fire:.2f} m")
    print(f"params.h: DRY_MASS_KG={v.dry_mass_kg:.3f} INERTIA_KGM2={ib:.3f} "
          f"GIMBAL_LEVER_M={v.gimbal_station_m - cgb:.3f} CDA_PRE_M2={g.cda_pre_m2:.5f} "
          f"CDA_BURN_M2={g.cda_burn_m2:.5f} CDA_LEGS_M2={g.cda_legs_m2:.5f}")


if __name__ == "__main__":
    main()
